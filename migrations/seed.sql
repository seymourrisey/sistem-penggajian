-- SEED DATA: Sistem Informasi Penggajian
-- Sumber data: Kaggle 'Employee Salary Dataset' (prince7489)
-- https://www.kaggle.com/datasets/prince7489/employee-salary-dataset
-- Transformasi diterapkan (lihat docs/data-provenance.md untuk detail):
--  1. Department -> departemen.nama (dipakai apa adanya dari dataset)
--  2. Experience_Years -> jabatan (tier: 0-2 Staff, 3-7 Staff Senior,
--     8-15 Manager, 16+ Senior Manager)
--  3. Monthly_Salary (INR) -> gaji_pokok (IDR): TIDAK dikonversi kurs.
--     Nilai asli diubah jadi percentile rank (0..1) lalu di-remap linear
--     ke skala gaji Indonesia realistis Rp5.000.000 - Rp35.000.000.
--     Alasan: nilai INR tidak representatif untuk skala gaji lokal;
--     yang dipertahankan dari dataset adalah *distribusi relatif* gaji
--     antar-karyawan, bukan nilai absolutnya.
--  4. Name, Education_Level, Age, City, Gender -> TIDAK dipakai.
--     Name diganti nama Indonesia sintetis (dataset asli generik:
--     'Employee_1', dst). Field lain tidak ada padanan di skema.
--  5. NIP, tanggal_masuk -> sintetis penuh (tidak ada di dataset).
--     tanggal_masuk diturunkan dari Experience_Years (today - N tahun,
--     +/- random 0-300 hari) sebagai proxy masuk kerja.
-- =========================================================

